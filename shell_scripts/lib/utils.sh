#!/bin/bash
# =============================================================================
# utils.sh - ユーティリティ関数
# =============================================================================

# -----------------------------------------------------------------------------
# ログ出力
# -----------------------------------------------------------------------------

# 処理の開始時にメッセージを表示します。
# 引数:
#   $1: message - 表示するメッセージ
log_info() {
    echo "----------------------------------------"
    echo "$1"
    echo "----------------------------------------"
}

# エラーメッセージを表示して終了します。
# 引数:
#   $1: message - エラーメッセージ
#   $2: exit_code - 終了コード (オプション、デフォルト: 1)
log_error() {
    local message="$1"
    local exit_code="${2:-1}"
    echo "ERROR: $message" >&2
    exit "$exit_code"
}

# -----------------------------------------------------------------------------
# グラフリスト生成
# -----------------------------------------------------------------------------

# 実験対象となるグラフのリストをCSVファイルとして生成します。
# グローバル変数の使用:
#   $OUTPUT_CSV, $TYPE, $START, $STEP, $END
# 戻り値:
#   0: 成功
#   1: 失敗
generate_graph_list() {
    log_info "グラフリストを ${OUTPUT_CSV} に生成中..."

    # CSVヘッダーの書き込み
    echo "name,type,n,path" >"$OUTPUT_CSV" || {
        log_error "CSVファイルの作成に失敗しました: $OUTPUT_CSV"
    }

    # グラフリストの生成
    for n in $(seq -f "%04g" "$START" "$STEP" "$END"); do
        for i in $(seq -w 0 19); do
            echo "node_n=${n}_$i.json,$TYPE,$n,$TYPE/$n/node_n=${n}_$i.json" >>"$OUTPUT_CSV"
        done
    done

    log_info "グラフリストの生成が完了しました"
    return 0
}

# -----------------------------------------------------------------------------
# 制約フラグの設定
# -----------------------------------------------------------------------------

# VIOLATION_TYPEに基づいて制約フラグを設定します。
# 引数:
#   $1: violation_type - 制約違反タイプ (例: "overlap")
# グローバル変数の設定:
#   $OVERLAP_FLAG - 共通フラグ（WebCoLa以外）
#   $WEBCOLA_OVERLAP_FLAG - WebCoLa専用フラグ
setup_constraint_flags() {
    local violation_type="$1"
    
    if [ "$violation_type" = "overlap" ]; then
        OVERLAP_FLAG="--overlap-removal"
        WEBCOLA_OVERLAP_FLAG="--overlapRemoval"
    else
        OVERLAP_FLAG=""
        WEBCOLA_OVERLAP_FLAG=""
    fi
}

# -----------------------------------------------------------------------------
# ディレクトリ作成
# -----------------------------------------------------------------------------

# 必要なディレクトリを作成します。
# 引数:
#   $@: 作成するディレクトリのパス
ensure_directory() {
    for dir in "$@"; do
        if [ ! -d "$dir" ]; then
            mkdir -p "$dir" || {
                log_error "ディレクトリの作成に失敗しました: $dir"
            }
        fi
    done
}
